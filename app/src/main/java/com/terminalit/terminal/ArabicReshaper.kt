    private val LAM_ALEF_FORMS = mapOf(
        0x0644_0622 to listOf(0xFEF5, 0xFEF6),
        0x0644_0623 to listOf(0xFEF7, 0xFEF8),
        0x0644_0625 to listOf(0xFEF9, 0xFEFA),
        0x0644_0627 to listOf(0xFEFB, 0xFEFC)
