    private val DIACRITICS = setOf(
        0x064B, 0x064C, 0x064D, 0x064E, 0x064F,
        0x0650, 0x0651, 0x0652, 0x0653, 0x0654,
        0x0655, 0x0656, 0x0657, 0x0658, 0x0659,
        0x065A, 0x065B, 0x065C, 0x065D, 0x065E,
        0x065F, 0x0670
