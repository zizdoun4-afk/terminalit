    private const val ISOLATED = 0
    private const val FINAL = 1
    private const val INITIAL = 2
    private const val MEDIAL = 3

    fun reshape(text: String): String {
        if (!containsArabic(text)) return text

        val chars = text.codePoints().toArray()
        if (chars.isEmpty()) return text

        val result = mutableListOf<Int>()

        var i = 0
        while (i < chars.size) {
            val cp = chars[i]

            // Handle Lam + Alef ligatures
            if (i + 1 < chars.size && cp == 0x0644) {
                val next = chars[i + 1]
                if (!DIACRITICS.contains(next)) {
                    val ligatureKey = (cp shl 16) or next
                    val ligature = LAM_ALEF_FORMS[ligatureKey]
                    if (ligature != null) {
                        val prevJoin = getJoiningType(getPrevChar(chars, i))
                        val nextJoin = getJoiningType(getNextNonDiacriticChar(chars, i + 2))
                        val formIdx = if (nextJoin == 'D') 1 else 0
                        result.add(ligature[formIdx])
                        i += 2
                        continue
                    }
                }
            }

            val presForm = presentationForms[cp]
            if (presForm != null) {
                val prevChar = getPrevNonDiacriticChar(chars, i)
                val nextChar = getNextNonDiacriticChar(chars, i)
                val prevJoin = getJoiningType(prevChar)
                val nextJoin = getJoiningType(nextChar)

                val formIdx = when {
                    prevJoin == 'D' && nextJoin == 'D' -> MEDIAL
                    prevJoin == 'D' -> FINAL
                    nextJoin == 'D' -> INITIAL
                    else -> ISOLATED
                }

                result.add(presForm[formIdx])
            } else {
                result.add(cp)
            }

            i++
        }

        return String(result.toIntArray(), 0, result.size)
    }

    fun classifyDirection(text: String): Int {
        val bidi = Bidi(text, Bidi.DIRECTION_DEFAULT_LEFT_TO_RIGHT)
        return bidi.baseLevel
    }

    private fun containsArabic(text: String): Boolean {
        for (c in text) {
            if (c.code in 0x0600..0x06FF ||
                c.code in 0x0750..0x077F ||
                c.code in 0x08A0..0x08FF ||
                c.code in 0xFB50..0xFDFF ||
                c.code in 0xFE70..0xFEFF
            ) return true
        }
        return false
    }

    private fun getJoiningType(cp: Int): Char {
        return joiningTypes[cp] ?: 'U'
    }

    private fun getPrevChar(chars: IntArray, i: Int): Int {
        if (i <= 0) return -1
        return chars[i - 1]
    }

    private fun getPrevNonDiacriticChar(chars: IntArray, i: Int): Int {
        var j = i - 1
        while (j >= 0) {
            if (!DIACRITICS.contains(chars[j])) return chars[j]
            j--
        }
        return -1
    }

    private fun getNextNonDiacriticChar(chars: IntArray, i: Int): Int {
        var j = i + 1
        while (j < chars.size) {
            if (!DIACRITICS.contains(chars[j])) return chars[j]
            j++
        }
        return -1
    }
